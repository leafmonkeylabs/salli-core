#!/usr/bin/env node
// Writes src/skills/bundled.ts from the skills in skills/, so `salli skills
// install` carries them inside the CLI: a standalone binary has no files
// beside it to copy from.
//
//   node scripts/bundle-skills.mjs          regenerate
//   node scripts/bundle-skills.mjs --check  exit 1 if it is out of date
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = join(root, 'skills');
const outFile = join(root, 'src', 'skills', 'bundled.ts');

function filesUnder(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? filesUnder(path) : [path];
    });
}

function description(skillMd, name) {
  const front = /^---\n([\s\S]*?)\n---/.exec(skillMd);
  const line = front?.[1].split('\n').find((l) => l.startsWith('description:'));
  if (!line) throw new Error(`skills/${name}/SKILL.md has no description in its front matter`);
  return line.slice('description:'.length).trim();
}

const skills = readdirSync(skillsDir)
  .sort()
  .filter((name) => statSync(join(skillsDir, name)).isDirectory())
  .map((name) => {
    const dir = join(skillsDir, name);
    const files = Object.fromEntries(
      filesUnder(dir).map((path) => [relative(dir, path).split(sep).join('/'), readFileSync(path, 'utf8')]),
    );
    if (!files['SKILL.md']) throw new Error(`skills/${name} has no SKILL.md`);
    return { name, description: description(files['SKILL.md'], name), files };
  });

const source = `// Generated by scripts/bundle-skills.mjs from packages/cli/skills. Do not edit:
// change the skills, then run \`npm run generate:skills --workspace @leafmonkeylabs/salli\`.

export interface BundledSkill {
  /** The skill's directory name, as agents find it. */
  name: string;
  description: string;
  /** Path within the skill (forward slashes) → text. */
  files: Readonly<Record<string, string>>;
}

export const BUNDLED_SKILLS: readonly BundledSkill[] = ${JSON.stringify(skills, null, 2)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    // Missing counts as out of date.
  }
  if (current !== source) {
    console.error('src/skills/bundled.ts is out of date: run `npm run generate:skills --workspace @leafmonkeylabs/salli`.');
    process.exit(1);
  }
} else {
  writeFileSync(outFile, source);
  console.log(`Bundled ${skills.length} skills into ${relative(root, outFile)}`);
}
